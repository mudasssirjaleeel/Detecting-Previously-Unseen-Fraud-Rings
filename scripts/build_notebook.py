class _Display:
    def __init__(self):
        self.outputs = []


def run(cells, workdir):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    os.makedirs(workdir, exist_ok=True)
    os.chdir(workdir)
    sys.path.insert(0, workdir)
    ns = {"__name__": "__main__"}
    n = 0
    for c in cells:
        if c["cell_type"] != "code":
            continue
        n += 1
        c["execution_count"] = n
        src = c["source"]
        outs = []

        def display(obj):
            if hasattr(obj, "to_html"):
                outs.append({"output_type": "display_data", "metadata": {},
                             "data": {"text/html": obj.to_html(), "text/plain": str(obj)}})
            else:
                outs.append({"output_type": "display_data", "metadata": {}, "data": {"text/plain": str(obj)}})
        ns["display"] = display

        def show(*a, **k):
            buf = io.BytesIO()
            plt.gcf().savefig(buf, format="png", dpi=90, bbox_inches="tight")
            plt.close("all")
            outs.append({"output_type": "display_data", "metadata": {},
                         "data": {"image/png": base64.b64encode(buf.getvalue()).decode(), "text/plain": "<Figure>"}})
        plt.show = show
        stdout = io.StringIO()
        try:
            with contextlib.redirect_stdout(stdout):
                if src.startswith("%%writefile"):
                    first, body = src.split("\n", 1)
                    path = first.split(maxsplit=1)[1]
                    open(path, "w").write(body + "\n")
                    print(f"Writing {path}")
                else:
                    import ast
                    tree = ast.parse(src)
                    last = tree.body[-1] if tree.body and isinstance(tree.body[-1], ast.Expr) else None
                    if last is not None:
                        tree.body = tree.body[:-1]
                    exec(compile(tree, f"<cell {n}>", "exec"), ns)
                    if last is not None:
                        val = eval(compile(ast.Expression(last.value), f"<cell {n}>", "eval"), ns)
                        if val is not None:
                            res = {"output_type": "execute_result", "execution_count": n, "metadata": {},
                                   "data": {"text/plain": str(val)}}
                            if hasattr(val, "to_html"):
                                res["data"]["text/html"] = val.to_html()
                            outs.append(res)
        except Exception:
            outs.append({"output_type": "error", "ename": "Error", "evalue": "see traceback",
                         "traceback": traceback.format_exc().splitlines()})
            print(traceback.format_exc(), file=sys.stderr)
            c["outputs"] = ([{"output_type": "stream", "name": "stdout", "text": stdout.getvalue()}]
                            if stdout.getvalue() else []) + outs
            raise
        text = stdout.getvalue()
        c["outputs"] = ([{"output_type": "stream", "name": "stdout", "text": text}] if text else []) + outs
        print(f"cell {n} ok", file=sys.stderr, flush=True)


def save(path):
    nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                                       "language_info": {"name": "python"}},
          "nbformat": 4, "nbformat_minor": 5}
    for c in nb["cells"]:
        c["source"] = c["source"].splitlines(keepends=True)
        if c["cell_type"] == "code":
            for o in c["outputs"]:
                if o.get("output_type") == "stream":
                    o["text"] = o["text"].splitlines(keepends=True)
    json.dump(nb, open(path, "w"), indent=1)


if __name__ == "__main__":
    out = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "CORAL_fraud_rings.ipynb")
    if "--execute" in sys.argv:
        run(cells, os.path.join(os.path.dirname(out), "nb_run"))
    save(out)
    print("saved", out)
